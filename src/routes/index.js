const express = require('express');
const auth = require('../controllers/authController');
const books = require('../controllers/bookController');
const loans = require('../controllers/loanController');
const { requireAuth, requireAdmin } = require('../middlewares/auth');
const router = express.Router();
router.get('/health', (_, res) => res.json({ ok: true, app: 'BiblioWeb' }));
router.post('/auth/register', auth.register);
router.post('/auth/login', auth.login);
router.post('/auth/logout', requireAuth, auth.logout);
router.get('/auth/me', requireAuth, auth.me);
router.get('/books', requireAuth, books.list);
router.get('/books/:id', requireAuth, books.byId);
router.post('/books', requireAuth, requireAdmin, books.create);
router.patch('/books/:id', requireAuth, requireAdmin, books.update);
router.put('/books/:id', requireAuth, requireAdmin, books.update);
router.delete('/books/:id', requireAuth, requireAdmin, books.remove);
router.get('/loans', requireAuth, loans.list);
router.post('/loans', requireAuth, loans.create);
router.patch('/loans/:id/return', requireAuth, loans.returnLoan);
module.exports = router;
